#!/usr/bin/env python3
"""Share NetworkDiagramStudio's diagram engine with Config Inspector.

NetworkDiagramStudio (NDS) builds network pages (core network, site map, port maps, wireless,
VLANs and routing) from configurations and monitoring exports, and writes Visio files. This
script bundles its importers and diagram engine (NDS src/web) into webview/nds_engine.js, a
classic script that defines `NDSEngine`. The generated file is not edited by hand: change the
engine in NDS and run this again.

    python3 scripts/sync-nds-engine.py /path/to/NetworkDiagramStudio [--check]

It needs Node.js and network access to the npm registry for the pinned esbuild.
--check fails when the generated file differs from what the given NDS checkout produces.
"""
import subprocess
import sys
import tempfile
from pathlib import Path

ESBUILD = 'esbuild@0.25.10'
EXPORTS = [
    ('buildPages,exportVisio,printDocument', 'diagram/index.mjs'),
    ('readSources,composeEvidence,ensureEvidence,categories', 'evidence.mjs'),
    ('applyAutomaticOrder', 'device-hierarchy.mjs'),
    ('newPageSetup', 'page-options.mjs'),
]
NOTICES = ['imports/NETBOX-LICENSE.txt']


def bundle(nds):
    web = (nds / 'src' / 'web').resolve()
    try:
        commit = subprocess.run(['git', '-C', str(nds), 'rev-parse', '--short', 'HEAD'], capture_output=True, text=True, check=True).stdout.strip()
    except Exception:
        commit = 'unknown'
    with tempfile.TemporaryDirectory() as tmp:
        entry = Path(tmp) / 'entry.mjs'
        entry.write_text(''.join("export {%s} from '%s';\n" % (names, (web / module).as_posix()) for names, module in EXPORTS), encoding='utf-8')
        out = Path(tmp) / 'out.js'
        subprocess.run(['npx', '--yes', ESBUILD, str(entry), '--bundle', '--format=iife', '--global-name=NDSEngine', '--minify', '--charset=utf8',
                        '--legal-comments=none', '--log-level=warning', '--outfile=' + str(out)], check=True, cwd=tmp)
        code = out.read_text(encoding='utf-8')
    if '</script' in code.lower():
        raise SystemExit('The bundle contains a closing script tag and cannot be embedded.')
    notices = ''.join('/*\n' + (web / name).read_text(encoding='utf-8').replace('*/', '* /').strip() + '\n*/\n' for name in NOTICES)
    return ('// Generated by scripts/sync-nds-engine.py from NetworkDiagramStudio ' + commit + ' (src/web importers and diagram engine).\n'
            '// Shared with NetworkDiagramStudio. Do not edit by hand: change the engine there and run the script again.\n' + notices + code)


def main():
    args = [a for a in sys.argv[1:] if a != '--check']
    if len(args) != 1:
        raise SystemExit(__doc__)
    target = Path(__file__).resolve().parent.parent / 'webview' / 'nds_engine.js'
    text = bundle(Path(args[0]))
    if '--check' in sys.argv:
        if not target.exists() or target.read_text(encoding='utf-8') != text:
            raise SystemExit('webview/nds_engine.js is out of date: run scripts/sync-nds-engine.py')
        print('webview/nds_engine.js matches the NetworkDiagramStudio checkout')
        return
    target.write_text(text, encoding='utf-8')
    print('Wrote', target, len(text), 'bytes')


if __name__ == '__main__':
    main()
