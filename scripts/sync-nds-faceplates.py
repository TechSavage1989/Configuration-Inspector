#!/usr/bin/env python3
"""Share NetworkDiagramStudio's device drawings with Config Inspector.

NetworkDiagramStudio (NDS) keeps a library of researched front panels (models, port positions, aspect
ratios) and draws them as plain shapes. This script bundles the NDS modules that draw them into
webview/nds_faceplates.js, a classic script exposing `NDSFaceplates` (deviceFaceplate, faceplateProfile,
genericDeviceSymbol, faceplates). The generated file is not edited by hand: change the drawings in NDS
and run this again.

    python3 scripts/sync-nds-faceplates.py /path/to/NetworkDiagramStudio [--check]

--check fails when the generated file differs from what the given NDS checkout produces.
"""
import re
import subprocess
import sys
from pathlib import Path

MODULES = [
    'imports/researched-layouts.mjs',
    'imports/faceplates.mjs',
    'device-symbols.mjs',
    'diagram/connector-geometry.mjs',
    'diagram/faceplate.mjs',
]
API = {
    'deviceFaceplate': 'diagram/faceplate.mjs',
    'faceplateProfile': 'diagram/faceplate.mjs',
    'genericDeviceSymbol': 'device-symbols.mjs',
    'faceplates': 'imports/faceplates.mjs',
}
IMPORT = re.compile(r"^import\s*\{([^}]*)\}\s*from\s*'([^']+)';\s*$", re.M)
EXPORT = re.compile(r'^export\s+(function|const|let)\s+([A-Za-z_$][\w$]*)', re.M)


def resolve(module, target):
    base = Path(module).parent
    parts = []
    for piece in (base / target).as_posix().split('/'):
        if piece == '..':
            parts.pop()
        elif piece not in ('', '.'):
            parts.append(piece)
    return '/'.join(parts)


def bundle(nds):
    web = nds / 'src' / 'web'
    try:
        commit = subprocess.run(['git', '-C', str(nds), 'rev-parse', '--short', 'HEAD'], capture_output=True, text=True, check=True).stdout.strip()
    except Exception:
        commit = 'unknown'
    out = ['// Generated by scripts/sync-nds-faceplates.py from NetworkDiagramStudio ' + commit + ' (src/web: ' + ', '.join(MODULES) + ').',
           '// Device drawings shared with NetworkDiagramStudio. Do not edit by hand: change them there and run the script again.',
           '(function(root){\'use strict\';var __m={};']
    for module in MODULES:
        code = (web / module).read_text(encoding='utf-8')
        names = []

        def imp(match):
            pairs = []
            for item in match.group(1).split(','):
                item = item.strip()
                if not item:
                    continue
                if ' as ' in item:
                    a, b = [s.strip() for s in item.split(' as ')]
                    pairs.append(a + ':' + b)
                else:
                    pairs.append(item)
            dep = resolve(module, match.group(2))
            if dep not in MODULES:
                raise SystemExit(module + ' imports ' + dep + ', which is not bundled: add it to MODULES.')
            return 'const {' + ','.join(pairs) + '}=__m[' + repr(dep) + '];'

        code = IMPORT.sub(imp, code)

        def exp(match):
            names.append(match.group(2))
            return match.group(1) + ' ' + match.group(2)

        code = EXPORT.sub(exp, code)
        if re.search(r'^\s*(import|export)\b', code, re.M):
            raise SystemExit(module + ' uses an import or export form this script does not handle.')
        out.append('__m[' + repr(module) + ']=(function(){\n' + code.rstrip() + '\nreturn {' + ','.join(names) + '};})();')
    api = ','.join(name + ':__m[' + repr(module) + '].' + name for name, module in API.items())
    out.append("var api={" + api + ",source:'NetworkDiagramStudio " + commit + "'};")
    out.append("root.NDSFaceplates=api;if(typeof module==='object'&&module.exports)module.exports=api;")
    out.append("})(typeof globalThis!=='undefined'?globalThis:this);")
    return '\n'.join(out) + '\n'


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    if len(args) != 1:
        raise SystemExit(__doc__)
    nds = Path(args[0]).resolve()
    target = Path(__file__).resolve().parent.parent / 'webview' / 'nds_faceplates.js'
    text = bundle(nds)
    if '--check' in sys.argv:
        current = target.read_text(encoding='utf-8') if target.exists() else ''
        strip = lambda s: s.split('\n', 1)[1] if s.startswith('// Generated') else s
        if strip(current) != strip(text):
            raise SystemExit('webview/nds_faceplates.js differs from ' + str(nds) + ': run scripts/sync-nds-faceplates.py.')
        print('webview/nds_faceplates.js matches ' + str(nds))
        return
    target.write_text(text, encoding='utf-8')
    print('Wrote ' + str(target) + ' (' + str(len(text)) + ' bytes)')


if __name__ == '__main__':
    main()
